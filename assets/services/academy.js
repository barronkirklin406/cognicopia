function yearRecord(a, learnerId, year) {
    const l = learnerOf(a, learnerId);
    if (!l) return null;
    const mine = a.progress[l.id] || {}, done = [];
    let inProgress = 0;
    Object.keys(mine).forEach((mid)=>{
        const m = moduleOf(mid), p = mine[mid];
        if (!m) return;
        if (p.completedAt && new Date(p.completedAt).getFullYear() === year) done.push({
            module: m,
            progress: p
        });
        else if (!p.completedAt && (p.played.length || p.read || p.video || p.quizAttempts)) inProgress++;
    });
    done.sort((x, y)=>x.progress.completedAt < y.progress.completedAt ? -1 : 1);
    return {
        learner: l,
        minutes: done.reduce((n, d)=>n + d.progress.minutes, 0),
        completed: done,
        inProgress
    };
}
