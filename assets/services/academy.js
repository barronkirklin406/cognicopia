function coverage(m, p) {
    if (p.read) return 1;
    if (m.video && m.video.src) return p.video;
    const c = cues(m), total = c.reduce((s, q)=>s + q.dur, 0);
    const got = p.played.reduce((s, i)=>s + (c[i] ? c[i].dur : 0), 0);
    return total ? Math.min(1, got / total) : 0;
}
