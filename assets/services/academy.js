function cues(m) {
    const out = [];
    let t = 0;
    m.chapters.forEach((c, ci)=>{
        [
            c.title + "."
        ].concat(c.say).forEach((text, k)=>{
            const dur = Math.max(2, Math.round(words(text) * 60 / WPM * 10) / 10) + (k === 0 ? 0.6 : 0.3);
            out.push({
                i: out.length,
                chapter: ci,
                title: k === 0,
                text: k === 0 ? c.title : text,
                start: Math.round(t * 10) / 10,
                dur
            });
            t += dur;
        });
    });
    return out;
}
