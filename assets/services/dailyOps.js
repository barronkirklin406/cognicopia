function paginate(secs, fit = 1) {
    const pages = [
        []
    ];
    let used = 0;
    const cur = ()=>pages[pages.length - 1];
    const fresh = ()=>{
        pages.push([]);
        used = 0;
    };
    for (const s of secs){
        if (!s.rows.length) {
            if (!s.empty) continue;
            if (used + HEAD_IN + EMPTY_IN > PAGE_BODY_IN && cur().length) fresh();
            cur().push({
                heading: s.heading,
                rows: [],
                cont: false,
                empty: s.empty
            });
            used += HEAD_IN + EMPTY_IN + SECTION_GAP_IN;
            continue;
        }
        let i = 0, first = true;
        while(i < s.rows.length){
            if (used + HEAD_IN + rowHeight(s.rows[i], fit) > PAGE_BODY_IN && cur().length) fresh();
            const piece = {
                heading: s.heading,
                rows: [],
                cont: !first,
                empty: ""
            };
            used += HEAD_IN;
            while(i < s.rows.length && (!piece.rows.length || used + rowHeight(s.rows[i], fit) <= PAGE_BODY_IN)){
                piece.rows.push(s.rows[i]);
                used += rowHeight(s.rows[i], fit);
                i++;
            }
            cur().push(piece);
            first = false;
            if (i < s.rows.length) fresh();
        }
        used += SECTION_GAP_IN;
    }
    return {
        pages,
        room: PAGE_BODY_IN - used
    };
}
