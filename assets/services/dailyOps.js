const MAX_WORDS = 6;
function nameTable(known) {
    const aliases = new Map();
    let longest = 1;
    const add = (target, alias)=>{
        const k = keyOf(target), words = k.split(/[ '-]/).length;
        if (k.length < 2 || words > MAX_WORDS) return;
        const set = aliases.get(k) || new Set();
        set.add(alias);
        aliases.set(k, set);
        if (words > longest) longest = words;
    };
    for (const k of known){
        const name = oneLine(k && k.name, 60), alias = oneLine(k && k.alias, LIMITS.ABOUT_CHARS) || "a resident";
        if (!name) continue;
        const words = name.split(/[\s,]+/).map((w)=>w.replace(/^[^\p{L}\p{N}]+|[^\p{L}\p{N}]+$/gu, "")).filter(Boolean);
        if (words.length > 1) add(words.join(" "), alias);
        words.filter((w)=>!HONORIFICS.has(fold(w))).forEach((w)=>{
            add(w, alias);
            if (/[-'’]/.test(w)) w.split(/[-'’]/).filter((p)=>p.length >= 3).forEach((p)=>add(p, alias));
        });
    }
    return {
        aliases,
        longest
    };
}
function scan(text, table) {
    const src = String(text == null ? "" : text).normalize("NFD");
    const toks = [];
    for (const m of src.matchAll(WORD_RE)){
        const s = m.index || 0;
        toks.push({
            k: fold(m[0]),
            t: m[0],
            s,
            e: s + m[0].length
        });
    }
    const gap = toks.map((t, i)=>i + 1 < toks.length ? sepClass(src.slice(t.e, toks[i + 1].s)) : "");
    const spans = [];
    for(let i = 0; i < toks.length; i++){
        for(let n = Math.min(table.longest, toks.length - i); n >= 1; n--){
            let key = toks[i].k, joined = true;
            for(let j = 1; j < n && joined; j++){
                if (gap[i + j - 1]) key += gap[i + j - 1] + toks[i + j].k;
                else joined = false;
            }
            const set = joined ? table.aliases.get(key) : undefined;
            if (set) {
                spans.push({
                    s: toks[i].s,
                    e: toks[i + n - 1].e,
                    hit: src.slice(toks[i].s, toks[i + n - 1].e),
                    repl: set.size === 1 ? Array.from(set)[0] : "a resident"
                });
                break;
            }
        }
        if (TITLES.has(toks[i].t) && gap[i] === " " && /^\p{Lu}/u.test(toks[i + 1].t) && toks[i + 1].t.replace(/\p{M}/gu, "").length >= 2) spans.push({
            s: toks[i].s,
            e: toks[i + 1].e,
            hit: src.slice(toks[i].s, toks[i + 1].e),
            repl: "[name]"
        });
    }
    spans.sort((a, b)=>a.s - b.s || b.e - b.s - (a.e - a.s));
    const hits = [];
    let out = "", at = 0;
    for (const sp of spans){
        if (sp.s < at) continue;
        out += src.slice(at, sp.s) + sp.repl;
        at = sp.e;
        const shown = sp.hit.normalize("NFC");
        if (!hits.some((h)=>h.toLowerCase() === shown.toLowerCase())) hits.push(shown);
    }
    return {
        hits,
        fixed: hits.length ? (out + src.slice(at)).normalize("NFC") : String(text == null ? "" : text)
    };
}
