function clashOf(plan, s) {
    return plan.slots.filter((x)=>x.id !== s.id && x.group === s.group && x.date === s.date && x.time === s.time)[0] || null;
}
function moveSlot(plan, slotId, toDate, toTime, lock = false) {
    const s = plan.slots.filter((x)=>x.id === slotId)[0];
    if (!s || monthDays(plan.month).indexOf(toDate) < 0) return {
        plan,
        swapped: null,
        moved: null
    };
    const time = toTime && isTime(toTime) ? toTime : s.time;
    if (toDate === s.date && time === s.time) return {
        plan,
        swapped: null,
        moved: null
    };
    const other = clashOf(plan, {
        id: s.id,
        group: s.group,
        date: toDate,
        time
    });
    const moved = Object.assign({}, s, {
        date: toDate,
        time,
        locked: s.locked || lock
    });
    const swapped = other ? Object.assign({}, other, {
        date: s.date,
        time: s.time,
        locked: other.locked || lock
    }) : null;
    const slots = plan.slots.map((x)=>x.id === s.id ? moved : swapped && x.id === swapped.id ? swapped : x);
    return {
        plan: Object.assign({}, plan, {
            slots: sortSlots(slots)
        }),
        swapped,
        moved
    };
}
function updateSlot(plan, slot) {
    const fit = fitOf(slot.activity);
    if (!fit || !ID.test(slot.id) || !ID.test(slot.group) || !isTime(slot.time) || monthDays(plan.month).indexOf(slot.date) < 0 || clashOf(plan, slot)) return plan;
    const isNew = !plan.slots.some((x)=>x.id === slot.id);
    if (isNew && plan.slots.length >= LIMITS.slots) return plan;
    const clean = {
        id: slot.id,
        date: slot.date,
        time: slot.time,
        group: slot.group,
        pillar: fit.pillar,
        activity: fit.id,
        locked: slot.locked === true,
        note: line(slot.note, 140)
    };
    return Object.assign({}, plan, {
        slots: sortSlots(plan.slots.filter((x)=>x.id !== clean.id).concat([
            clean
        ]))
    });
}
