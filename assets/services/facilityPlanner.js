function arrange(ps, times, cost) {
    let best = ps.slice(), bestCost = Infinity;
    const perm = (rest, acc)=>{
        if (!rest.length) {
            const c = acc.reduce((n, p, k)=>n + cost(p, times[k]), 0);
            if (c < bestCost) {
                bestCost = c;
                best = acc;
            }
            return;
        }
        rest.forEach((p, i)=>perm(rest.slice(0, i).concat(rest.slice(i + 1)), acc.concat([
                p
            ])));
    };
    perm(ps, []);
    return best;
}
function autoPopulate(plan, wing, opt = {}) {
    const days = monthDays(plan.month), groups = wing.groups.filter((g)=>!opt.groups || opt.groups.indexOf(g.id) >= 0);
    const target = new Set(groups.map((g)=>g.id));
    const kept = plan.slots.filter((s)=>s.locked || !target.has(s.group));
    const out = kept.slice();
    for (const g of groups){
        const r = rng((opt.seed || "1") + "|" + wing.id + "|" + g.id + "|" + plan.month);
        const recs = recommend(g.acuity, opt.available), byPillar = new Map(recs.map((x)=>[
                x.pillar.id,
                x.recommended
            ]));
        const pillars = PILLARS.map((p)=>p.id).filter((p)=>(byPillar.get(p) || []).length);
        const counts = new Map(pillars.map((p)=>[
                p,
                0
            ]));
        const used = new Map();
        const use = (id, day)=>{
            const l = used.get(id);
            if (l) l.push(day);
            else used.set(id, [
                day
            ]);
        };
        const gap = (id, day)=>(used.get(id) || []).reduce((m, d)=>Math.min(m, Math.abs(day - d)), 99);
        const mine = kept.filter((s)=>s.group === g.id);
        mine.forEach((s)=>{
            counts.set(s.pillar, (counts.get(s.pillar) || 0) + 1);
            use(s.activity, days.indexOf(s.date));
        });
        let yesterday = new Map();
        days.forEach((d, di)=>{
            const times = isWeekend(d) ? wing.cadence.weekend : wing.cadence.weekday;
            const fixed = mine.filter((s)=>s.date === d), today = fixed.map((s)=>s.pillar);
            const free = times.filter((t)=>!fixed.some((s)=>s.time === t)), before = new Set(yesterday.values());
            const chosen = [];
            free.forEach(()=>{
                let best = pillars[0], bestScore = Infinity;
                for (const p of pillars){
                    const sc = (counts.get(p) || 0) * 100 + (today.indexOf(p) >= 0 || chosen.indexOf(p) >= 0 ? 1000 : 0) + (before.has(p) ? 20 : 0) + r();
                    if (sc < bestScore) {
                        best = p;
                        bestScore = sc;
                    }
                }
                chosen.push(best);
                counts.set(best, (counts.get(best) || 0) + 1);
            });
            const order = arrange(chosen, free, (p, t)=>PREFER[p][partOfDay(t)] + (yesterday.get(t) === p ? 12 : 0));
            const todayAt = new Map(fixed.map((s)=>[
                    s.time,
                    s.pillar
                ]));
            free.forEach((t, k)=>{
                const best = order[k], options = byPillar.get(best) || [];
                let act = options[0], actScore = Infinity;
                options.forEach((a, rank)=>{
                    const since = gap(a.id, di);
                    const sc = (since < 7 ? (7 - since) * 50 : 0) - Math.min(since, 60) + rank * 2 + r();
                    if (sc < actScore) {
                        act = a;
                        actScore = sc;
                    }
                });
                todayAt.set(t, best);
                use(act.id, di);
                out.push({
                    id: "s-" + hash(wing.id + g.id + d + t + (opt.seed || "")).toString(36) + Math.floor(r() * 1e6).toString(36),
                    date: d,
                    time: t,
                    group: g.id,
                    pillar: best,
                    activity: act.id,
                    locked: false,
                    note: ""
                });
            });
            yesterday = todayAt;
        });
    }
    return {
        v: 1,
        wing: plan.wing,
        month: plan.month,
        slots: sortSlots(out)
    };
}
