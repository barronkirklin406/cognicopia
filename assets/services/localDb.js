const DB_NAME = "CognicopiaLocalDB";
const DB_VERSION = 1;
const STORE_RESIDENTS = "residents";
const STORE_PACKETS = "generatedPackets";
/** The three care levels a profile can have. */
const TIERS                    = ["Mild", "Moderate", "Advanced"];
/** The most a saved packet's HTML may hold (characters). A page is a few hundred KB; this is a guard, not a target. */
