/* ---------- Audio Engine ---------- */
class NostalgiaRadioEngine {
          audioContext                      = null;
          masterGain                  = null;
          activeNodes                           = new Map();
          isPlaying          = false;
          currentSoundscape                    = null;
          timerId                = null;
          volume         = 0.5;

  constructor() {
    if (typeof window !== "undefined") {
      this.initAudioContext();
    }
  }

          initAudioContext()       {
    if (typeof window === "undefined" || !window.AudioContext) return;
    
    // AudioContext will be created on first user gesture
    this.audioContext = null;
  }

          ensureAudioContext()               {
    if (!this.audioContext) {
      this.audioContext = new (window.AudioContext || (window       ).webkitAudioContext)();
    }
    
    if (this.audioContext.state === "suspended") {
      this.audioContext.resume();
    }
    
    return this.audioContext;
  }

          createMasterGain()           {
    const ctx = this.ensureAudioContext();
    const gain = ctx.createGain();
    gain.gain.value = this.volume;
    gain.connect(ctx.destination);
    return gain;
  }

          ensureMasterGain()           {
    if (!this.masterGain) {
      this.masterGain = this.createMasterGain();
    }
    return this.masterGain;
  }

          stopAllNodes()       {
    this.activeNodes.forEach((nodes) => {
      nodes.forEach(node => {
        try {
          node.disconnect();
        } catch (e) {
          // Ignore disconnect errors
        }
      });
    });
    this.activeNodes.clear();
  }

  /* ---------- Volume fading ---------- */
          fadeIn(duration         = 2000)       {
    const gain = this.ensureMasterGain();
    const ctx = this.ensureAudioContext();
    const now = ctx.currentTime;
    
    gain.gain.cancelScheduledValues(now);
    gain.gain.setValueAtTime(0, now);
    gain.gain.linearRampToValueAtTime(this.volume, now + duration / 1000);
  }

          fadeOut(duration         = 2000)       {
    const gain = this.masterGain;
    if (!gain) return;
    
    const ctx = this.ensureAudioContext();
    const now = ctx.currentTime;
    
    gain.gain.cancelScheduledValues(now);
    gain.gain.setValueAtTime(gain.gain.value, now);
    gain.gain.linearRampToValueAtTime(0, now + duration / 1000);
  }

  /* ---------- Soundcape generators ---------- */
          generateTrainSoundscape(ctx              , destination           )              {
    const nodes              = [];
    
    // Low rumble (distant train)
    const rumbleOsc = ctx.createOscillator();
    const rumbleGain = ctx.createGain();
    rumbleOsc.type = "sawtooth";
    rumbleOsc.frequency.value = 60;
    rumbleGain.gain.value = 0.15;
    rumbleOsc.connect(rumbleGain);
    rumbleGain.connect(destination);
    rumbleOsc.start();
    nodes.push(rumbleOsc, rumbleGain);
    
    // Rhythmic chugging (train wheels)
    const chugOsc = ctx.createOscillator();
    const chugGain = ctx.createGain();
    const chugLFO = ctx.createOscillator();
    const chugLFOGain = ctx.createGain();
    
    chugOsc.type = "square";
    chugOsc.frequency.value = 80;
    chugGain.gain.value = 0.08;
    
    chugLFO.frequency.value = 2; // 2 Hz chugging
    chugLFOGain.gain.value = 1;
    
    chugLFO.connect(chugLFOGain);
    chugLFOGain.connect(chugGain.gain);
    chugOsc.connect(chugGain);
    chugGain.connect(destination);
    
    chugOsc.start();
    chugLFO.start();
    nodes.push(chugOsc, chugGain, chugLFO, chugLFOGain);
    
    // Occasional whistle (using FM synthesis)
    const whistleOsc = ctx.createOscillator();
    const whistleGain = ctx.createGain();
    const whistleLFO = ctx.createOscillator();
    
    whistleOsc.type = "sine";
    whistleOsc.frequency.value = 800;
    whistleGain.gain.value = 0;
    
    whistleLFO.frequency.value = 0.5; // Whistle every 2 seconds
    whistleLFO.type = "square";
    
    // Modulate whistle gain
    const whistleEnvelope = ctx.createGain();
    whistleEnvelope.gain.value = 0;
    
    // Create whistle pattern
    const now = ctx.currentTime;
    for (let i = 0; i < 10; i++) {
      const whistleTime = now + i * 4;
      whistleGain.gain.setValueAtTime(0, whistleTime);
      whistleGain.gain.linearRampToValueAtTime(0.2, whistleTime + 0.1);
      whistleGain.gain.linearRampToValueAtTime(0.15, whistleTime + 0.3);
      whistleGain.gain.linearRampToValueAtTime(0, whistleTime + 0.8);
    }
    
    whistleOsc.connect(whistleGain);
    whistleGain.connect(destination);
    whistleOsc.start();
    nodes.push(whistleOsc, whistleGain);
    
    return nodes;
  }

          generateRainSoundscape(ctx              , destination           )              {
    const nodes              = [];
    
    // White noise for rain
    const bufferSize = 2 * ctx.sampleRate;
    const noiseBuffer = ctx.createBuffer(1, bufferSize, ctx.sampleRate);
    const output = noiseBuffer.getChannelData(0);
    
    for (let i = 0; i < bufferSize; i++) {
      output[i] = Math.random() * 2 - 1;
    }
    
    const whiteNoise = ctx.createBufferSource();
    whiteNoise.buffer = noiseBuffer;
    whiteNoise.loop = true;
    
    // Filter for gentle rain (high-pass to remove low rumble)
    const rainFilter = ctx.createBiquadFilter();
    rainFilter.type = "highpass";
    rainFilter.frequency.value = 1000;
    rainFilter.Q.value = 1;
    
    const rainGain = ctx.createGain();
    rainGain.gain.value = 0.12;
    
    whiteNoise.connect(rainFilter);
    rainFilter.connect(rainGain);
    rainGain.connect(destination);
    whiteNoise.start();
    nodes.push(whiteNoise, rainFilter, rainGain);
    
    // Tin roof patter (filtered noise with amplitude modulation)
    const roofNoise = ctx.createBufferSource();
    roofNoise.buffer = noiseBuffer;
    roofNoise.loop = true;
    
    const roofFilter = ctx.createBiquadFilter();
    roofFilter.type = "bandpass";
    roofFilter.frequency.value = 2000;
    roofFilter.Q.value = 5;
    
    const roofGain = ctx.createGain();
    roofGain.gain.value = 0.08;
    
    const roofLFO = ctx.createOscillator();
    roofLFO.frequency.value = 8; // Fast patter
    const roofLFOGain = ctx.createGain();
    roofLFOGain.gain.value = 0.5;
    
    roofLFO.connect(roofLFOGain);
    roofLFOGain.connect(roofGain.gain);
    
    roofNoise.connect(roofFilter);
    roofFilter.connect(roofGain);
    roofGain.connect(destination);
    
    roofNoise.start();
    roofLFO.start();
    nodes.push(roofNoise, roofFilter, roofGain, roofLFO, roofLFOGain);
    
    // Hearth crackle (filtered noise with random amplitude)
    const crackleNoise = ctx.createBufferSource();
    crackleNoise.buffer = noiseBuffer;
    crackleNoise.loop = true;
    
    const crackleFilter = ctx.createBiquadFilter();
    crackleFilter.type = "lowpass";
    crackleFilter.frequency.value = 400;
    crackleFilter.Q.value = 2;
    
    const crackleGain = ctx.createGain();
    crackleGain.gain.value = 0.05;
    
    // Random crackle amplitude
    const crackleLFO = ctx.createOscillator();
    crackleLFO.frequency.value = 3;
    crackleLFO.type = "sawtooth";
    const crackleLFOGain = ctx.createGain();
    crackleLFOGain.gain.value = 0.8;
    
    crackleLFO.connect(crackleLFOGain);
    crackleLFOGain.connect(crackleGain.gain);
    
    crackleNoise.connect(crackleFilter);
    crackleFilter.connect(crackleGain);
    crackleGain.connect(destination);
    
    crackleNoise.start();
    crackleLFO.start();
    nodes.push(crackleNoise, crackleFilter, crackleGain, crackleLFO, crackleLFOGain);
    
    return nodes;
  }

          generateBarnSoundscape(ctx              , destination           )              {
    const nodes              = [];
    
    // Pink noise approximation for barn ambience
    const bufferSize = 2 * ctx.sampleRate;
    const noiseBuffer = ctx.createBuffer(1, bufferSize, ctx.sampleRate);
    const output = noiseBuffer.getChannelData(0);
    
    // Pink noise approximation
    let b0 = 0, b1 = 0, b2 = 0, b3 = 0, b4 = 0, b5 = 0, b6 = 0;
    for (let i = 0; i < bufferSize; i++) {
      const white = Math.random() * 2 - 1;
      b0 = 0.99886 * b0 + white * 0.0555179;
      b1 = 0.99332 * b1 + white * 0.0750759;
      b2 = 0.96900 * b2 + white * 0.1538520;
      b3 = 0.86650 * b3 + white * 0.3104856;
      b4 = 0.55000 * b4 + white * 0.5329522;
      b5 = -0.7616 * b5 - white * 0.0168980;
      output[i] = b0 + b1 + b2 + b3 + b4 + b5 + b6 + white * 0.5362;
      output[i] *= 0.11;
      b6 = white * 0.115926;
    }
    
    const barnNoise = ctx.createBufferSource();
    barnNoise.buffer = noiseBuffer;
    barnNoise.loop = true;
    
    const barnFilter = ctx.createBiquadFilter();
    barnFilter.type = "lowpass";
    barnFilter.frequency.value = 800;
    barnFilter.Q.value = 0.5;
    
    const barnGain = ctx.createGain();
    barnGain.gain.value = 0.15;
    
    barnNoise.connect(barnFilter);
    barnFilter.connect(barnGain);
    barnGain.connect(destination);
    barnNoise.start();
    nodes.push(barnNoise, barnFilter, barnGain);
    
    // Bird chirps (sine wave sweeps)
    const birdOsc = ctx.createOscillator();
    const birdGain = ctx.createGain();
    const birdLFO = ctx.createOscillator();
    
    birdOsc.type = "sine";
    birdOsc.frequency.value = 2000;
    birdGain.gain.value = 0;
    
    birdLFO.frequency.value = 0.3; // Chirp every 3 seconds
    birdLFO.type = "square";
    
    // Chirp pattern
    const now = ctx.currentTime;
    for (let i = 0; i < 8; i++) {
      const chirpTime = now + i * 3.3;
      birdGain.gain.setValueAtTime(0, chirpTime);
      birdGain.gain.linearRampToValueAtTime(0.08, chirpTime + 0.05);
      birdGain.gain.linearRampToValueAtTime(0, chirpTime + 0.15);
      
      birdOsc.frequency.setValueAtTime(1800 + Math.random() * 400, chirpTime);
      birdOsc.frequency.linearRampToValueAtTime(2200 + Math.random() * 400, chirpTime + 0.1);
    }
    
    birdOsc.connect(birdGain);
    birdGain.connect(destination);
    birdOsc.start();
    nodes.push(birdOsc, birdGain);
    
    // Distant animal sounds (low frequency rumble)
    const animalOsc = ctx.createOscillator();
    const animalGain = ctx.createGain();
    
    animalOsc.type = "sine";
    animalOsc.frequency.value = 120;
    animalGain.gain.value = 0.05;
    
    animalOsc.connect(animalGain);
    animalGain.connect(destination);
    animalOsc.start();
    nodes.push(animalOsc, animalGain);
    
    return nodes;
  }

          generateRadioSoundscape(ctx              , destination           )              {
    const nodes              = [];
    
    // Radio static (white noise)
    const bufferSize = 2 * ctx.sampleRate;
    const noiseBuffer = ctx.createBuffer(1, bufferSize, ctx.sampleRate);
    const output = noiseBuffer.getChannelData(0);
    
    for (let i = 0; i < bufferSize; i++) {
      output[i] = Math.random() * 2 - 1;
    }
    
    const staticNoise = ctx.createBufferSource();
    staticNoise.buffer = noiseBuffer;
    staticNoise.loop = true;
    
    const staticFilter = ctx.createBiquadFilter();
    staticFilter.type = "bandpass";
    staticFilter.frequency.value = 3000;
    staticFilter.Q.value = 1;
    
    const staticGain = ctx.createGain();
    staticGain.gain.value = 0.06;
    
    staticNoise.connect(staticFilter);
    staticFilter.connect(staticGain);
    staticGain.connect(destination);
    staticNoise.start();
    nodes.push(staticNoise, staticFilter, staticGain);
    
    // Big band music (simplified using multiple oscillators)
    // Bass line
    const bassOsc = ctx.createOscillator();
    const bassGain = ctx.createGain();
    const bassLFO = ctx.createOscillator();
    
    bassOsc.type = "triangle";
    bassOsc.frequency.value = 80;
    bassGain.gain.value = 0.08;
    
    bassLFO.frequency.value = 2; // Walking bass
    bassLFO.type = "square";
    
    bassLFO.connect(bassGain.gain);
    bassOsc.connect(bassGain);
    bassGain.connect(destination);
    
    bassOsc.start();
    bassLFO.start();
    nodes.push(bassOsc, bassGain, bassLFO);
    
    // Horn melody (sine wave with vibrato)
    const hornOsc = ctx.createOscillator();
    const hornGain = ctx.createGain();
    const hornVibrato = ctx.createOscillator();
    
    hornOsc.type = "sine";
    hornOsc.frequency.value = 440;
    hornGain.gain.value = 0.04;
    
    hornVibrato.frequency.value = 5;
    hornVibrato.type = "sine";
    const hornVibratoGain = ctx.createGain();
    hornVibratoGain.gain.value = 10;
    
    hornVibrato.connect(hornVibratoGain);
    hornVibratoGain.connect(hornOsc.frequency);
    
    // Simple melody pattern
    const now = ctx.currentTime;
    const melody = [440, 494, 523, 587, 523, 494, 440, 392]; // A major scale
    melody.forEach((freq, i) => {
      const noteTime = now + i * 0.5;
      hornOsc.frequency.setValueAtTime(freq, noteTime);
    });
    
    hornOsc.connect(hornGain);
    hornGain.connect(destination);
    
    hornOsc.start();
    hornVibrato.start();
    nodes.push(hornOsc, hornGain, hornVibrato, hornVibratoGain);
    
    // Gentle rhythm (snare approximation)
    const rhythmOsc = ctx.createOscillator();
    const rhythmGain = ctx.createGain();
    const rhythmLFO = ctx.createOscillator();
    
    rhythmOsc.type = "square";
    rhythmOsc.frequency.value = 200;
    rhythmGain.gain.value = 0;
    
    rhythmLFO.frequency.value = 2; // 2 BPM
    rhythmLFO.type = "square";
    
    // Pattern: backbeat
    for (let i = 0; i < 8; i++) {
      const beatTime = now + i * 0.5;
      if (i % 2 === 1) { // Backbeat
        rhythmGain.gain.setValueAtTime(0, beatTime);
        rhythmGain.gain.linearRampToValueAtTime(0.03, beatTime + 0.05);
        rhythmGain.gain.linearRampToValueAtTime(0, beatTime + 0.1);
      }
    }
    
    rhythmOsc.connect(rhythmGain);
    rhythmGain.connect(destination);
    
    rhythmOsc.start();
    rhythmLFO.start();
    nodes.push(rhythmOsc, rhythmGain, rhythmLFO);
    
    return nodes;
  }

  /* ---------- Public API ---------- */
  play(soundscape            )       {
    this.stop();
    
    const ctx = this.ensureAudioContext();
    const destination = this.ensureMasterGain();
    
    let nodes              = [];
    
    switch (soundscape) {
      case "train":
        nodes = this.generateTrainSoundscape(ctx, destination);
        break;
      case "rain":
        nodes = this.generateRainSoundscape(ctx, destination);
        break;
      case "barn":
        nodes = this.generateBarnSoundscape(ctx, destination);
        break;
      case "radio":
        nodes = this.generateRadioSoundscape(ctx, destination);
        break;
    }
    
    this.activeNodes.set(soundscape, nodes);
    this.currentSoundscape = soundscape;
    this.isPlaying = true;
    this.fadeIn(2000);
  }

  stop()       {
    if (!this.isPlaying) return;
    
    this.fadeOut(1500);
    
    setTimeout(() => {
      this.stopAllNodes();
      this.isPlaying = false;
      this.currentSoundscape = null;
    }, 1500);
  }

  setVolume(value        )       {
    this.volume = Math.max(0, Math.min(1, value));
    if (this.masterGain) {
      this.masterGain.gain.value = this.volume;
    }
  }

  getVolume()         {
    return this.volume;
  }

  isCurrentlyPlaying()          {
    return this.isPlaying;
  }

  getCurrentSoundscape()                    {
    return this.currentSoundscape;
  }

  setTimer(minutes        )       {
    this.clearTimer();
    
    if (minutes > 0) {
      this.timerId = window.setTimeout(() => {
        this.stop();
      }, minutes * 60 * 1000);
    }
  }

  clearTimer()       {
    if (this.timerId !== null) {
      clearTimeout(this.timerId);
      this.timerId = null;
    }
  }

  getSoundscapeDef(id            )                       {
    return SOUNDSCAPES.find(s => s.id === id) || null;
  }

  getAllSoundscapes()                           {
    return SOUNDSCAPES;
  }

  dispose()       {
    this.stop();
    this.clearTimer();
    if (this.audioContext) {
      this.audioContext.close();
      this.audioContext = null;
    }
    this.masterGain = null;
  }
}

