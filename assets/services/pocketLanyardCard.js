    static saveBackToProfile(data) {
        if (!data.id && typeof window !== "undefined" && window.residentId) {
            data.id = window.residentId;
        }
        const id = data.id;
        if (!id || typeof window === "undefined" || !window.localStorage) return false;
        const key = "cognicopia_resident_" + id;
        try {
            const raw = window.localStorage.getItem(key);
            if (!raw) return false;
            const profile = JSON.parse(raw);
            if (!profile || !profile.tier1_core) return false;
            profile.tier1_core.topicsToAvoid = profile.tier1_core.topicsToAvoid || {};
            profile.tier1_core.topicsToAvoid.other = data.triggers.join("; ");
            if (data.preferredName && data.preferredName !== profile.tier1_core.preferredName) {
                profile.tier1_core.alias = data.preferredName;
            }
            if (data.unitNumber) {
                profile.tier1_core.unitNumber = data.unitNumber;
            }
            profile.updatedAt = new Date().toISOString();
            window.localStorage.setItem(key, JSON.stringify(profile));
            if (typeof window.toast === "function") {
                window.toast("Saved pocket card triggers & soothing topics to " + profile.tier1_core.preferredName + "'s profile.");
            }
            return true;
        } catch (e) {
            console.warn("Could not save to resident profile:", e);
            return false;
        }
    }
