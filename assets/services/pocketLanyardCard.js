function extractPocketCardData(profile) {
    const p = profile || {};
    const t1 = p.tier1_core || {};
    const t2 = p.tier2_enrichment || {};
    const t3 = p.tier3_deep || {};
    const fullName = (t1.preferredName || p.preferredName || p.name || "Resident").trim();
    const alias = (t1.alias || p.alias || "").trim();
    const unitNumber = (t1.unitNumber || p.unitNumber || "").trim();
    const tier = t1.cognitiveTier || p.cognitiveTier || p.tier || 2;
    const rawTriggers = [];
    if (t1.topicsToAvoid) {
        if (Array.isArray(t1.topicsToAvoid.topics)) {
            t1.topicsToAvoid.topics.forEach((top)=>{
                const lbl = typeof top === "string" ? top : top.label || top.code || "";
                if (lbl) rawTriggers.push(lbl);
            });
        }
        if (t1.topicsToAvoid.other && typeof t1.topicsToAvoid.other === "string") {
            const parts = t1.topicsToAvoid.other.split(/[,;\n]+/).map((s)=>s.trim()).filter(Boolean);
            rawTriggers.push(...parts);
        }
    }
    if (t3.notes && typeof t3.notes === "string") {
        const notesLower = t3.notes;
        const triggerMatch = notesLower.match(/(?:frustrat|agit|upset|avoids?|dislikes?|fear|trigger)[^.\n]*[.:]\s*([^.\n]+)/i);
        if (triggerMatch && triggerMatch[1]) {
            rawTriggers.push(triggerMatch[1].trim());
        }
    }
    const defaultTriggers = [
        "Sudden loud noises & crowded hallway transitions",
        "Rushing or approaching unexpectedly from behind",
        "Direct confrontation or arguing with time-confusion"
    ];
    const triggers = [
        rawTriggers[0] || defaultTriggers[0],
        rawTriggers[1] || defaultTriggers[1],
        rawTriggers[2] || defaultTriggers[2]
    ];
    const rawSoothers = [];
    if (Array.isArray(t3.people)) {
        const pets = t3.people.filter((x)=>x && (x.isPet || x.relationship && x.relationship.code && x.relationship.code.indexOf("pet") !== -1));
        if (pets.length > 0) {
            rawSoothers.push(`Ask about ${pets[0].name || "her pet"} (fond companion memory)`);
        }
        const lovedOnes = t3.people.filter((x)=>x && !x.isPet && !x.passedAway && x.name);
        if (lovedOnes.length > 0 && rawSoothers.length < 2) {
            rawSoothers.push(`Mention loved one ${lovedOnes[0].name} (${lovedOnes[0].relationship && lovedOnes[0].relationship.label || "family"})`);
        }
    }
    const deescalation = p.preselectedDeescalationActivity;
    if (deescalation === "silhouette-match") {
        rawSoothers.push("Offer calming silhouette shadow matching sheet");
    } else if (deescalation === "letter-tracing") {
        rawSoothers.push(`Hand letter-tracing page with preferred name (${fullName})`);
    } else if (deescalation === "line-tracing") {
        rawSoothers.push("Hand fine-motor calming line-tracing activity");
    }
    if (Array.isArray(t1.topHobbies)) {
        t1.topHobbies.forEach((h)=>{
            const hName = typeof h === "string" ? h : h.label || h.code || "";
            if (hName && rawSoothers.length < 3) {
                rawSoothers.push(`Talk about ${hName.toLowerCase()} memories & experiences`);
            }
        });
    }
    if (t2.music) {
        if (t2.music.favoriteSong && rawSoothers.length < 3) {
            rawSoothers.push(`Play or hum favorite song: "${t2.music.favoriteSong}"`);
        } else if (Array.isArray(t2.music.artists) && t2.music.artists.length > 0 && rawSoothers.length < 3) {
            rawSoothers.push(`Listen to or reminisce about ${t2.music.artists[0]}`);
        }
    }
    if (t1.occupation && rawSoothers.length < 3) {
        const job = t1.occupation.label || t1.occupation.code || "";
        if (job && job.toLowerCase() !== "other") {
            rawSoothers.push(`Ask for advice on ${job.toLowerCase()} work`);
        }
    }
    const defaultSoothers = [
        "Ask about hometown memories & favorite foods",
        "Hand soothing warm beverage & soft visual activity sheet",
        "Invite to help fold towels or organize familiar items"
    ];
    const soothingTopics = [
        rawSoothers[0] || defaultSoothers[0],
        rawSoothers[1] || defaultSoothers[1],
        rawSoothers[2] || defaultSoothers[2]
    ];
    let decadesStr = "";
    if (Array.isArray(t2.meaningfulDecades) && t2.meaningfulDecades.length > 0) {
        const list = t2.meaningfulDecades.map((d)=>typeof d === "string" ? d : d.code || d.label || "").filter(Boolean);
        if (list.length === 1) {
            decadesStr = list[0];
        } else if (list.length > 1) {
            decadesStr = `${list[0]}–${list[list.length - 1]}`;
        }
    }
    if (!decadesStr) {
        decadesStr = "1950s–1960s";
    }
    const occLabel = t1.occupation && t1.occupation.label ? t1.occupation.label : "";
    const petName = Array.isArray(t3.people) ? t3.people.find((x)=>x && x.isPet)?.name || "" : "";
    let keyAnchor = "";
    if (occLabel && petName) {
        keyAnchor = `${occLabel} · Pet: ${petName}`;
    } else if (occLabel) {
        keyAnchor = `Vocation: ${occLabel}`;
    } else if (petName) {
        keyAnchor = `Beloved Pet: ${petName}`;
    } else {
        keyAnchor = `Hometown: ${t2.hometown && t2.hometown.place || "Midwest"} (${decadesStr})`;
    }
    const approachRule = "Approach face-to-face at eye level · Use calm, warm, low-pitched voice · Never argue or correct confusion";
    return {
        id: p.id || undefined,
        residentName: fullName,
        preferredName: alias ? `${fullName} ("${alias}")` : fullName,
        unitNumber: unitNumber,
        cognitiveTier: tier,
        triggers: triggers,
        soothingTopics: soothingTopics,
        reminiscenceDecades: decadesStr,
        careNotesOrRule: approachRule,
        keyVocationOrPet: keyAnchor
    };
}
