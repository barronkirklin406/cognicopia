function formatRef(r) {
    const who = r.authors.length ? authorList(r.authors) + ". " : "";
    if (r.kind === "book") return `${who}${r.title}. ${r.publisher || r.source}; ${r.year}.`;
    if (r.kind === "regulation" && !r.authors.length) return `${r.title}. ${r.source}. Accessed ${fmtDate(REVIEWED)}.${r.url ? " " + r.url : ""}`;
    if (r.url && !r.volume && !r.doi) return `${who}${r.title}. ${r.source}${r.year ? "; " + r.year : ""}. Accessed ${fmtDate(REVIEWED)}. ${r.url}`;
    const vol = r.volume ? `;${r.volume}${r.issue ? `(${r.issue})` : ""}${r.pages ? ":" + r.pages : ""}` : "";
    return `${who}${r.title}. ${r.source}. ${r.year}${vol}.${r.doi ? " doi:" + r.doi : ""}`;
}
function shortRef(r) {
    if (r.short) return r.short;
    if (!r.authors.length) return r.title.replace(/:.*$/, "");
    const first = r.authors[0], named = r.authors.filter((x)=>x !== "et al");
    const surname = (s)=>/\s[A-Z]{1,3}( Jr)?$/.test(s) ? s.replace(/\s[A-Z]{1,3}( Jr)?$/, "") : s;
    if (named.length === 1 && r.authors.length === 1) return `${surname(first)}, ${r.year}`;
    if (named.length === 2 && r.authors.length === 2) return `${surname(first)} & ${surname(named[1])}, ${r.year}`;
    return `${surname(first)} et al., ${r.year}`;
}
