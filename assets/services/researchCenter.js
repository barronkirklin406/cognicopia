function draw(doc, page) {
    for (const o of page.ops){
        const c = o.rgb || INK;
        if (o.t === "text") {
            doc.setFont("helvetica", o.bold && o.italic ? "bolditalic" : o.bold ? "bold" : o.italic ? "italic" : "normal");
            doc.setFontSize(o.size || 10.5);
            doc.setTextColor(c[0], c[1], c[2]);
            doc.text(String(o.text || ""), o.x, o.y, {
                align: o.align || "left"
            });
        } else if (o.t === "rule") {
            doc.setDrawColor(c[0], c[1], c[2]);
            doc.setLineWidth(o.lw || 1);
            doc.line(o.x, o.y, o.x2 == null ? o.x : o.x2, o.y2 == null ? o.y : o.y2);
        } else if (o.t === "box") {
            doc.setDrawColor(c[0], c[1], c[2]);
            doc.setLineWidth(o.lw || 1);
            doc.rect(o.x, o.y, o.w || 0, o.h || 0, "S");
        } else {
            doc.setFillColor(c[0], c[1], c[2]);
            doc.rect(o.x, o.y, o.w || 0, o.h || 0, "F");
        }
    }
}
