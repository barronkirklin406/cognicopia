function boardLayout(blocks, split, footer) {
    const { w, h, m } = PAGE, W = w - m * 2, bottom = h - m - 18;
    const pages = [];
    let ops = [], y = m;
    const newPage = ()=>{
        pages.push({
            w,
            h,
            ops
        });
        ops = [];
        y = m;
    };
    const lines = (text, width, size, bold = false)=>split(text, width, size, bold);
    const text = (t, x, yy, size, o = {})=>{
        ops.push(Object.assign({
            t: "text",
            x,
            y: yy,
            text: t,
            size,
            rgb: INK
        }, o));
    };
    const para = (t, x, width, size, lead, o = {})=>{
        lines(t, width, size, !!o.bold).forEach((ln)=>{
            if (y + size * lead > bottom) {
                newPage();
            }
            y += size * lead;
            text(ln, x, y, size, o);
        });
    };
    const heightOf = (b)=>{
        switch(b.k){
            case "h1":
                return 20 * 1.2 + 20;
            case "h2":
                return 12.5 * 1.25 + 14;
            case "p":
                return lines(b.text, W, 10.5).length * 10.5 * 1.45 + 6;
            case "small":
                return lines(b.text, W, 9).length * 9 * 1.4 + 6;
            case "li":
                return lines(b.text, W - 16, 10.5).length * 10.5 * 1.45 + 3;
            case "field":
                return Math.max(1, lines(b.label, W * 0.58, 10.5, true).length) * 10.5 * 1.4 + (b.note ? lines(b.note, W * 0.58, 8.5).length * 8.5 * 1.35 : 0) + 12;
            case "callout":
                return lines(b.title, W - 28, 11, true).length * 11 * 1.35 + lines(b.text, W - 28, 10.5).length * 10.5 * 1.45 + 26;
            case "ref":
                return lines(b.text, W - 22, 9).length * 9 * 1.4 + 3;
            case "gap":
                return b.h;
            default:
                return 0;
        }
    };
    const table = (b)=>{
        const size = 9.5, lead = 1.35, pad = 5, xs = [], ws = b.widths.map((f)=>f * W);
        ws.reduce((x, cw)=>{
            xs.push(x);
            return x + cw;
        }, m);
        const rowH = (cells, bold)=>{
            const ls = cells.map((c, k)=>lines(c, ws[k] - pad * 2, size, bold || k === 0));
            return {
                ls,
                hh: Math.max(...ls.map((l)=>l.length)) * size * lead + pad * 2
            };
        };
        const drawRow = (cells, head)=>{
            const r = rowH(cells, head);
            if (y + r.hh > bottom) {
                newPage();
                if (!head) drawRow(b.head, true);
            }
            if (head) ops.push({
                t: "fill",
                x: m,
                y,
                w: W,
                h: r.hh,
                rgb: HEAD
            });
            r.ls.forEach((ls, k)=>ls.forEach((ln, j)=>text(ln, xs[k] + pad, y + pad + (j + 1) * size * lead - 2.5, size, {
                        bold: head || k === 0
                    })));
            y += r.hh;
            ops.push({
                t: "rule",
                x: m,
                y,
                x2: m + W,
                y2: y,
                lw: head ? 1 : 0.6,
                rgb: head ? GREEN : RULE
            });
        };
        const first = rowH(b.head, true).hh + (b.rows.length ? rowH(b.rows[0], false).hh : 0);
        if (y + first > bottom && y > m) newPage();
        drawRow(b.head, true);
        b.rows.forEach((r)=>drawRow(r, false));
        y += 10;
    };
    blocks.forEach((b, bi)=>{
        if (b.k === "cover") {
            if (ops.length) newPage();
            ops.push({
                t: "fill",
                x: 0,
                y: 0,
                w,
                h: 250,
                rgb: GREEN
            });
            text("COGNICOPIA", m, 86, 12, {
                bold: true,
                rgb: [
                    197,
                    230,
                    211
                ]
            });
            y = 128;
            lines(b.title, W, 30, true).forEach((ln)=>{
                text(ln, m, y, 30, {
                    bold: true,
                    rgb: WHITE
                });
                y += 36;
            });
            text("Clinical Science & Research Center · Board packet", m, 222, 11, {
                rgb: [
                    216,
                    236,
                    224
                ]
            });
            y = 300;
            b.lines.forEach((ln, k)=>lines(ln, W, k === 0 ? 15 : 11.5, k === 0).forEach((l)=>{
                    text(l, m, y, k === 0 ? 15 : 11.5, {
                        bold: k === 0,
                        rgb: k === 2 ? MUTED : INK
                    });
                    y += k === 0 ? 22 : 17;
                }));
            y += 18;
            text("Contents", m, y, 13, {
                bold: true,
                rgb: GREEN
            });
            y += 8;
            ops.push({
                t: "rule",
                x: m,
                y,
                x2: m + W,
                y2: y,
                lw: 1,
                rgb: GREEN
            });
            b.contents.forEach((c)=>{
                y += 21;
                text(c, m, y, 11.5);
            });
            const note = lines(b.note, W, 9.5);
            let ny = h - m - 30 - note.length * 13;
            ops.push({
                t: "rule",
                x: m,
                y: ny - 10,
                x2: m + W,
                y2: ny - 10,
                lw: 0.6,
                rgb: RULE
            });
            note.forEach((ln)=>{
                ny += 13;
                text(ln, m, ny, 9.5, {
                    rgb: MUTED
                });
            });
            newPage();
            return;
        }
        if (b.k === "break") {
            if (ops.length) newPage();
            return;
        }
        if (b.k === "table") {
            table(b);
            return;
        }
        let need = heightOf(b);
        const next = blocks[bi + 1];
        if ((b.k === "h1" || b.k === "h2") && next) need += next.k === "table" ? 80 : Math.min(heightOf(next), 50);
        if (y + need > bottom && y > m) newPage();
        switch(b.k){
            case "h1":
                y += 20;
                text(b.text, m, y, 20, {
                    bold: true,
                    rgb: GREEN
                });
                y += 10;
                ops.push({
                    t: "rule",
                    x: m,
                    y,
                    x2: m + W,
                    y2: y,
                    lw: 1.5,
                    rgb: GREEN
                });
                y += 10;
                break;
            case "h2":
                y += 10;
                para(b.text, m, W, 12.5, 1.25, {
                    bold: true,
                    rgb: GREEN
                });
                y += 4;
                break;
            case "p":
                para(b.text, m, W, 10.5, 1.45);
                y += 6;
                break;
            case "small":
                para(b.text, m, W, 9, 1.4, {
                    rgb: MUTED
                });
                y += 6;
                break;
            case "li":
                {
                    const ls = lines(b.text, W - 16, 10.5);
                    ls.forEach((ln, k)=>{
                        if (y + 15.2 > bottom) newPage();
                        y += 10.5 * 1.45;
                        if (k === 0) text("•", m + 3, y, 10.5, {
                            bold: true,
                            rgb: GREEN
                        });
                        text(ln, m + 16, y, 10.5);
                    });
                    y += 3;
                    break;
                }
            case "field":
                {
                    const top = y, lw = W * 0.58, ls = lines(b.label, lw, 10.5, true);
                    ls.forEach((ln)=>{
                        y += 10.5 * 1.4;
                        text(ln, m, y, 10.5, {
                            bold: true
                        });
                    });
                    if (b.note) lines(b.note, lw, 8.5).forEach((ln)=>{
                        y += 8.5 * 1.35;
                        text(ln, m, y, 8.5, {
                            rgb: MUTED
                        });
                    });
                    const vy = top + 10.5 * 1.4;
                    if (b.value) text(b.value, m + W, vy, 11.5, {
                        bold: true,
                        align: "right"
                    });
                    else ops.push({
                        t: "rule",
                        x: m + W - 150,
                        y: vy + 2,
                        x2: m + W,
                        y2: vy + 2,
                        lw: 1,
                        rgb: INK
                    });
                    y += 8;
                    ops.push({
                        t: "rule",
                        x: m,
                        y,
                        x2: m + W,
                        y2: y,
                        lw: 0.4,
                        rgb: RULE
                    });
                    y += 4;
                    break;
                }
            case "callout":
                {
                    const tl = lines(b.title, W - 28, 11, true), bl = lines(b.text, W - 28, 10.5), hh = tl.length * 11 * 1.35 + bl.length * 10.5 * 1.45 + 18;
                    y += 4;
                    ops.push({
                        t: "fill",
                        x: m,
                        y,
                        w: W,
                        h: hh,
                        rgb: TINT
                    }, {
                        t: "fill",
                        x: m,
                        y,
                        w: 4,
                        h: hh,
                        rgb: GREEN
                    });
                    let yy = y + 4;
                    tl.forEach((ln)=>{
                        yy += 11 * 1.35;
                        text(ln, m + 16, yy, 11, {
                            bold: true,
                            rgb: GREEN
                        });
                    });
                    bl.forEach((ln)=>{
                        yy += 10.5 * 1.45;
                        text(ln, m + 16, yy, 10.5);
                    });
                    y += hh + 8;
                    break;
                }
            case "ref":
                {
                    const ls = lines(b.text, W - 22, 9);
                    ls.forEach((ln, k)=>{
                        if (y + 12.6 > bottom) newPage();
                        y += 9 * 1.4;
                        if (k === 0) text(b.n + ".", m, y, 9, {
                            bold: true
                        });
                        text(ln, m + 22, y, 9);
                    });
                    y += 3;
                    break;
                }
            case "gap":
                y += b.h;
                break;
        }
    });
    if (ops.length) pages.push({
        w,
        h,
        ops
    });
    const n = pages.length;
    pages.forEach((p, k)=>{
        if (k === 0) return;
        p.ops.push({
            t: "rule",
            x: m,
            y: h - m + 2,
            x2: w - m,
            y2: h - m + 2,
            lw: 0.5,
            rgb: RULE
        });
        p.ops.push({
            t: "text",
            x: m,
            y: h - m + 16,
            text: footer,
            size: 8.5,
            rgb: MUTED
        });
        p.ops.push({
            t: "text",
            x: w - m,
            y: h - m + 16,
            text: "Page " + (k + 1) + " of " + n,
            size: 8.5,
            rgb: MUTED,
            align: "right"
        });
    });
    return pages;
}
function boardFooter(facility, split) {
    const month = new Date(REVIEWED + "T12:00:00Z").toLocaleDateString("en-US", {
        month: "long",
        year: "numeric",
        timeZone: "UTC"
    });
    const make = (f)=>"Cognicopia board packet" + (f ? " · " + f : "") + " · Evidence reviewed " + month;
    const fits = (t)=>split(t, PAGE.w - PAGE.m * 2 - 84, 8.5, false).length === 1;
    let f = facility.trim(), t = make(f);
    while(!fits(t) && f.length > 1){
        const cut = f.lastIndexOf(" ");
        f = (cut > 0 ? f.slice(0, cut) : f.slice(0, -1)).replace(/[\s,;:·–—-]+$/, "");
        t = make(f + "…");
    }
    return fits(t) ? t : make("");
}
