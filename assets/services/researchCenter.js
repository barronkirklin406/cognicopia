function problems() {
    const out = [], slugs = DOCS.map((d)=>d.slug), used = new Set();
    if (new Set(slugs).size !== slugs.length) out.push("duplicate document slugs");
    if (new Set(REFS.map((r)=>r.id)).size !== REFS.length) out.push("duplicate reference ids");
    DOCS.forEach((d)=>{
        const texts = docTexts(d);
        texts.forEach((t)=>{
            citeKeys(t).forEach((k)=>{
                used.add(k);
                if (!refOf(k)) out.push(`${d.slug}: unknown reference ${k}`);
            });
            let m;
            LINK.lastIndex = 0;
            while(m = LINK.exec(t))if (!docOf(m[1])) out.push(`${d.slug}: link to unknown document ${m[1]}`);
        });
        if (!d.takeaways.length || !d.practice.length || !d.limits.length || !d.sections.length) out.push(`${d.slug}: missing takeaways, practice, limits or sections`);
        if (d.type === "case" && (d.level !== "illustrative" || !d.scenario)) out.push(`${d.slug}: a case scenario must be labeled illustrative`);
        if (d.level !== "illustrative" && !refsOf(d).length) out.push(`${d.slug}: cites no sources`);
        d.related.forEach((r)=>{
            if (!docOf(r) || r === d.slug) out.push(`${d.slug}: bad related ${r}`);
        });
        const ids = d.sections.map((s)=>s.id);
        if (new Set(ids).size !== ids.length) out.push(`${d.slug}: duplicate section ids`);
        d.figures.forEach((f)=>{
            if (!citeKeys(f.cite).length) out.push(`${d.slug}: a data citation block without a source`);
        });
    });
    BOARD_EVIDENCE.forEach((r)=>r.cite.forEach((k)=>{
            used.add(k);
            if (!refOf(k)) out.push(`board packet: unknown reference ${k}`);
        }));
    boardBlocks(normalizeBoard({})).refs.forEach((k)=>{
        used.add(k);
        if (!refOf(k)) out.push(`board packet: unknown reference ${k}`);
    });
    REFS.forEach((r)=>{
        if (!used.has(r.id)) out.push(`reference ${r.id} is never cited`);
    });
    return out;
}
