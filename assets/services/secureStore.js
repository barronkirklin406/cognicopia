function toB64(data) {
    const a = data instanceof Uint8Array ? data : new Uint8Array(data);
    let s = "";
    for(let i = 0; i < a.length; i += 0x8000)s += String.fromCharCode.apply(null, Array.from(a.subarray(i, i + 0x8000)));
    return btoa(s);
}
