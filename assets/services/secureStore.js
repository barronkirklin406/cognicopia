async function migrate() {
    const ls = env().ls;
    if (!ls) return;
    const found = [];
    try {
        for(let i = 0; i < ls.length; i++){
            const k = ls.key(i);
            if (k && isSealed(k)) {
                const v = ls.getItem(k);
                if (v != null) found.push([
                    k,
                    v
                ]);
            }
        }
    } catch  {
        return;
    }
    if (!found.length) return;
    found.forEach(([k, v])=>{
        S.mirror.set(k, v);
        S.pending.set(k, v);
    });
    await persist();
    found.forEach(([k, v])=>{
        try {
            if (ls.getItem(k) === v) ls.removeItem(k);
        } catch  {}
    });
    S.migrated += found.length;
    S.keysCache = null;
}
function schedule() {
    if (S.timer) return;
    S.timer = setTimeout(()=>{
        S.timer = 0;
        S.writing = S.writing.then(persist, persist);
    }, 0);
}
async function persist() {
    if (!S.db || !S.key || !S.pending.size) return;
    const batch = Array.from(S.pending.entries());
    S.pending.clear();
    const key = S.key;
    try {
        const sealed = await Promise.all(batch.map(([n, v])=>v == null ? Promise.resolve(null) : seal(key, n, v)));
        await tx(S.db, [
            RECORDS
        ], "readwrite", (t)=>{
            const st = t.objectStore(RECORDS);
            batch.forEach(([n], i)=>{
                const r = sealed[i];
                if (r) st.put(r, n);
                else st.delete(n);
            });
        });
        if (S.channel) S.channel.postMessage({
            type: "records",
            names: batch.map((b)=>b[0])
        });
        extendSession();
    } catch (err) {
        batch.forEach(([n, v])=>{
            if (!S.pending.has(n)) S.pending.set(n, v);
        });
        emit("error", {
            message: "Saved details could not be written: " + String(err.message || err)
        });
        throw err;
    }
}
function flush() {
    if (S.timer) {
        clearTimeout(S.timer);
        S.timer = 0;
        S.writing = S.writing.then(persist, persist);
    }
    return S.writing.catch(()=>undefined);
}
function extendSession() {
    if (!S.db || !S.key || !S.ring || S.ring.mode !== "passphrase" || S.unlockedUntil == null || S.keepMs <= 0) return;
    const t = Date.now();
    if (t - S.lastExtend < 60000) return;
    S.lastExtend = t;
    const session = {
        key: S.key,
        expires: t + S.keepMs,
        keepMs: S.keepMs
    };
    S.unlockedUntil = session.expires;
    tx(S.db, [
        RINGS
    ], "readwrite", (tr)=>{
        tr.objectStore(RINGS).put(session, "session");
    }).catch(()=>undefined);
}
