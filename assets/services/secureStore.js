async function deriveKek(pass, salt, rounds) {
    const s = env().subtle;
    const base = await s.importKey("raw", enc.encode(pass), "PBKDF2", false, [
        "deriveKey"
    ]);
    return s.deriveKey({
        name: "PBKDF2",
        hash: "SHA-256",
        salt: buf(salt),
        iterations: rounds
    }, base, AES, false, [
        "encrypt",
        "decrypt"
    ]);
}
async function seal(key, name, value) {
    const iv = bytes(12);
    const data = await env().subtle.encrypt({
        name: "AES-GCM",
        iv: buf(iv),
        additionalData: buf(enc.encode(name))
    }, key, enc.encode(value));
    return {
        iv,
        data,
        t: Date.now()
    };
}
async function unseal(key, name, r) {
    const plain = await env().subtle.decrypt({
        name: "AES-GCM",
        iv: buf(r.iv),
        additionalData: buf(enc.encode(name))
    }, key, r.data);
    return dec.decode(plain);
}
async function newDeviceKey() {
    return env().subtle.generateKey(AES, false, [
        "encrypt",
        "decrypt"
    ]);
}
async function wrapNewKey(pass, rounds) {
    const s = env().subtle, raw = bytes(32), salt = bytes(16), iv = bytes(12);
    try {
        const kek = await deriveKek(pass, salt, rounds);
        const wrapped = await s.encrypt({
            name: "AES-GCM",
            iv: buf(iv)
        }, kek, buf(raw));
        const key = await s.importKey("raw", buf(raw), AES, false, [
            "encrypt",
            "decrypt"
        ]);
        return {
            ring: {
                mode: "passphrase",
                salt,
                rounds,
                iv,
                wrapped,
                created: new Date().toISOString()
            },
            key
        };
    } finally{
        raw.fill(0);
    }
}
async function unwrapKey(ring, pass) {
    const s = env().subtle, kek = await deriveKek(pass, ring.salt, ring.rounds);
    let raw;
    try {
        raw = new Uint8Array(await s.decrypt({
            name: "AES-GCM",
            iv: buf(ring.iv)
        }, kek, ring.wrapped));
    } catch  {
        return null;
    }
    try {
        return await s.importKey("raw", buf(raw), AES, false, [
            "encrypt",
            "decrypt"
        ]);
    } finally{
        raw.fill(0);
    }
}
