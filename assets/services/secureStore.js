const clean = (v, max)=>String(v == null ? "" : v).replace(/[\u0000-\u001F\u007F<>]/g, "").replace(/\s+/g, " ").trim().slice(0, max);
const CODE_CHARS = "23456789ABCDEFGHJKMNPQRSTUVWXYZ";
function shortCode(id, length = 4) {
    let h = 0x811c9dc5;
    for(let i = 0; i < id.length; i++){
        h ^= id.charCodeAt(i);
        h = Math.imul(h, 0x01000193) >>> 0;
    }
    let out = "";
    for(let i = 0; i < length; i++){
        out += CODE_CHARS[h % CODE_CHARS.length];
        h = Math.floor(h / CODE_CHARS.length) || (h ^ 0x9e3779b9) >>> 0;
    }
    return out;
}
function aliasFor(p) {
    const t1 = p && p.tier1_core || {};
    const own = clean(t1.alias, 32);
    if (own) return own;
    const unit = clean(t1.unitNumber, 16).toUpperCase();
    if (unit) return "Resident " + unit;
    const id = typeof (p && p.id) === "string" ? String(p.id) : "";
    return "Resident " + (id ? shortCode(id) : "(no unit)");
}
function displayName(p, useAlias) {
    const name = clean(p && p.tier1_core ? p.tier1_core.preferredName : "", 40);
    return useAlias || !name ? aliasFor(p) : name;
}
const LOCKED_FORMAT = "cognicopia-locked";
const BACKUP_FORMAT = "cognicopia.residentBackup";
const PROFILE_SCHEMA = "cognicopia.residentProfile";
async function sealFile(obj, pass, kind, rounds = PBKDF2_ROUNDS) {
    const s = env().subtle;
    if (!s) throw new Error("This browser cannot lock files.");
    const salt = bytes(16), iv = bytes(12), key = await deriveKek(pass, salt, rounds);
    const data = await s.encrypt({
        name: "AES-GCM",
        iv: buf(iv)
    }, key, enc.encode(JSON.stringify(obj)));
    return {
        format: LOCKED_FORMAT,
        v: 1,
        kind,
        kdf: {
            name: "PBKDF2",
            hash: "SHA-256",
            iterations: rounds,
            salt: toB64(salt)
        },
        cipher: {
            name: "AES-GCM",
            length: 256,
            iv: toB64(iv)
        },
        data: toB64(data)
    };
}
const isLockedFile = (o)=>!!o && typeof o === "object" && o.format === LOCKED_FORMAT;
async function openFile(env0, pass) {
    const s = env().subtle;
    if (!s) throw new Error("This browser cannot open locked files.");
    if (!isLockedFile(env0)) throw new Error("format");
    const k = env0.kdf || {}, c = env0.cipher || {}, rounds = Number(k.iterations);
    if (env0.v !== 1 || k.name !== "PBKDF2" || k.hash !== "SHA-256" || c.name !== "AES-GCM" || !(rounds >= 100000 && rounds <= 5000000) || typeof env0.data !== "string") throw new Error("format");
    const key = await deriveKek(pass, fromB64(k.salt), rounds);
    let plain;
    try {
        plain = await s.decrypt({
            name: "AES-GCM",
            iv: buf(fromB64(c.iv))
        }, key, buf(fromB64(env0.data)));
    } catch  {
        throw new Error("passphrase");
    }
    return JSON.parse(dec.decode(plain));
}
const ID_RE = /^[A-Za-z0-9_-]{1,64}$/;
function isProfile(p) {
    if (!p || typeof p !== "object" || Array.isArray(p)) return false;
    const o = p;
    return o.schema === PROFILE_SCHEMA && typeof o.id === "string" && ID_RE.test(o.id) && !!o.tier1_core && typeof o.tier1_core.preferredName === "string" && !!o.tier1_core.preferredName.trim();
}
function rosterFile(profiles, station = "", note = "") {
    const list = profiles.filter(isProfile);
    const out = {
        format: BACKUP_FORMAT,
        version: 1,
        app: "Cognicopia",
        exportedAt: new Date().toISOString(),
        recordCount: list.length,
        profiles: list
    };
    if (station || note) out.handoff = {
        station: clean(station, 60),
        note: clean(note, 200)
    };
    return out;
}
async function exportRoster(profiles, pass, station = "", note = "") {
    const problem = passphraseProblem(pass);
    if (problem) throw new Error(problem);
    return sealFile(rosterFile(profiles, station, note), pass, "residents");
}
async function readRoster(text, pass) {
    let o;
    try {
        o = JSON.parse(text);
    } catch  {
        throw new Error("format");
    }
    if (isLockedFile(o)) {
        if (o.kind !== "residents") throw new Error("kind");
        o = await openFile(o, pass);
    }
    const r = o;
    if (!r || r.format !== BACKUP_FORMAT || !Array.isArray(r.profiles)) throw new Error("format");
    const profiles = r.profiles.filter(isProfile);
    return {
        profiles,
        skipped: r.profiles.length - profiles.length,
        exportedAt: String(r.exportedAt || ""),
        handoff: r.handoff || null
    };
}
function mergeRoster(existing, incoming, mode = "newer") {
    const byId = new Map();
    existing.forEach((p)=>{
        if (isProfile(p)) byId.set(p.id, p);
    });
    const stamp = (p)=>{
        const t = Date.parse(String(p.updatedAt || p.createdAt || ""));
        return Number.isFinite(t) ? t : 0;
    };
    const write = [];
    let added = 0, updated = 0, kept = 0;
    incoming.forEach((p)=>{
        if (!isProfile(p)) return;
        const have = byId.get(p.id);
        if (!have) {
            write.push(p);
            byId.set(p.id, p);
            added++;
            return;
        }
        if (mode === "skip" || mode === "newer" && stamp(p) <= stamp(have)) {
            kept++;
            return;
        }
        write.push(p);
        byId.set(p.id, p);
        updated++;
    });
    return {
        write,
        added,
        updated,
        kept
    };
}
