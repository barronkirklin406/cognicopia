function wrap(text, n) {
    const out = [];
    let cur = "";
    for (const w of text.split(" ")){
        if (w.length > n) {
            if (cur) out.push(cur);
            for(let i = 0; i < w.length; i += n)out.push(w.slice(i, i + n));
            cur = "";
            continue;
        }
        if (cur && (cur + " " + w).length > n) {
            out.push(cur);
            cur = w;
        } else cur = cur ? cur + " " + w : w;
    }
    if (cur) out.push(cur);
    return out.length ? out : [
        ""
    ];
}
function paginate(blocks, reserveLast = 0) {
    const pages = [
        []
    ];
    let used = 0;
    for (const b of blocks){
        const ls = b.paragraphs.flatMap((p)=>wrap(p, CHARS_PER_LINE));
        const room = (b.recorded ? 0 : EMPTY_IN) + (b.key === "checks" ? BOX_IN : 0);
        let i = 0, first = true;
        while(i < ls.length){
            const free = PAGE_BODY_IN - used - HEAD_IN - GAP_IN;
            const fit = Math.floor(free / LINE_IN);
            if (fit < 2 && pages[pages.length - 1].length) {
                pages.push([]);
                used = 0;
                continue;
            }
            const take = Math.max(1, Math.min(ls.length - i, fit));
            pages[pages.length - 1].push({
                heading: b.heading,
                text: ls.slice(i, i + take),
                cont: !first,
                empty: !b.recorded
            });
            used += HEAD_IN + GAP_IN + take * LINE_IN + (i + take >= ls.length ? room : 0);
            i += take;
            first = false;
            if (i < ls.length) {
                pages.push([]);
                used = 0;
            }
        }
    }
    if (reserveLast && used + reserveLast > PAGE_BODY_IN) pages.push([]);
    return pages;
}
