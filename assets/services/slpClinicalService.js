function checkSession(s) {
    const out = [], codes = s.codes.map((c)=>c.code);
    if (!s.date) out.push({
        level: "stop",
        text: "Add the session date."
    });
    if (!s.clinician) out.push({
        level: "warn",
        text: "Add who provided the session."
    });
    if (s.minutes == null) out.push({
        level: codes.some((c)=>(codeRef(c) || {
                timed: false
            }).timed) ? "stop" : "warn",
        text: "Record the session minutes."
    });
    for (const c of s.codes){
        const ref = codeRef(c.code);
        if (!ref) {
            out.push({
                level: "info",
                text: `${c.code} is not in this reference; check it against current CPT.`
            });
            continue;
        }
        if (!ref.cognitive) out.push({
            level: "stop",
            text: `${c.code}: ${ref.note}`
        });
        if (ref.addOnTo && codes.indexOf(ref.addOnTo) < 0) out.push({
            level: "stop",
            text: `${c.code} is an add-on and is reported with ${ref.addOnTo}.`
        });
        if (ref.group && s.format !== "group") out.push({
            level: "warn",
            text: `${c.code} is for group sessions; this session is recorded as individual.`
        });
        if (!ref.group && ref.code === "92507" && s.format === "group") out.push({
            level: "warn",
            text: "92507 is individual; group treatment is 92508."
        });
        if ((ref.code === "97129" || ref.code === "97130") && s.format === "group") out.push({
            level: "warn",
            text: `${ref.code} is direct one-on-one time; this session is recorded as group.`
        });
        if (ref.code === "96125" && !s.measures.some((m)=>/test|assessment|scale|inventory|exam|RIPA|SLUMS|MoCA|BCAT|CLQT|ABCD|SCATBI/i.test(m.task + " " + m.note))) out.push({
            level: "warn",
            text: "96125 is standardized testing: name the instrument in the objective section."
        });
        if (!ref.timed && c.units != null && c.units > 1) out.push({
            level: "warn",
            text: `${c.code} is untimed: one per session.`
        });
    }
    const timedUnits = s.codes.reduce((n, c)=>{
        const r = codeRef(c.code);
        return n + (r && r.timed && r.minutes === 15 ? c.units == null ? 1 : c.units : 0);
    }, 0);
    if (s.minutes != null && timedUnits && timedUnits * 15 - 7 > s.minutes) out.push({
        level: "warn",
        text: `${timedUnits} timed 15-minute unit${timedUnits === 1 ? "" : "s"} recorded for ${s.minutes} minutes: check the units against the time.`
    });
    if (!s.subjective && !s.measures.length && !s.assessment && !s.plan) out.push({
        level: "warn",
        text: "Nothing is recorded in S, O, A or P yet."
    });
    return out;
}
