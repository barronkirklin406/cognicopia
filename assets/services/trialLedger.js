function idbMirror(root) {
    const idb = root && root.indexedDB;
    if (!idb) return null;
    const open = ()=>new Promise((resolve, reject)=>{
            const q = idb.open(MIRROR_DB, 1);
            q.onupgradeneeded = ()=>{
                q.result.createObjectStore("k");
            };
            q.onsuccess = ()=>resolve(q.result);
            q.onerror = ()=>reject(q.error);
            q.onblocked = ()=>reject(new Error("blocked"));
        });
    return {
        name: "indexeddb",
        read: ()=>open().then((db)=>new Promise((resolve)=>{
                    const done = (v)=>{
                        try {
                            db.close();
                        } catch (e) {}
                        resolve(v);
                    };
                    try {
                        const r = db.transaction("k", "readonly").objectStore("k").get("n");
                        r.onsuccess = ()=>done(parseCount(r.result));
                        r.onerror = ()=>done(null);
                    } catch (e) {
                        done(null);
                    }
                })),
        write: (n)=>open().then((db)=>new Promise((resolve)=>{
                    const done = ()=>{
                        try {
                            db.close();
                        } catch (e) {}
                        resolve();
                    };
                    try {
                        const t = db.transaction("k", "readwrite"), st = t.objectStore("k"), g = st.get("n");
                        g.onsuccess = ()=>{
                            const cur = parseCount(g.result);
                            if (cur === null || cur < n) st.put(n, "n");
                        };
                        t.oncomplete = done;
                        t.onerror = done;
                        t.onabort = done;
                    } catch (e) {
                        done();
                    }
                }))
    };
}
function cacheMirror(root) {
    const caches = root && root.caches, loc = root && root.location;
    if (!caches || typeof root.Request !== "function" || typeof root.Response !== "function" || !loc || !loc.origin || loc.origin === "null") return null;
    const urlOf = (n)=>loc.origin + "/__cg_trial/" + n;
    return {
        name: "cache",
        read: ()=>caches.open(MIRROR_CACHE).then((c)=>c.keys()).then((keys)=>{
                let best = null;
                for (const k of keys){
                    const v = parseCount(String(k.url).split("/").pop());
                    if (v !== null && (best === null || v > best)) best = v;
                }
                return best;
            }),
        write: (n)=>caches.open(MIRROR_CACHE).then(async (c)=>{
                const keys = await c.keys();
                let best = null;
                for (const k of keys){
                    const v = parseCount(String(k.url).split("/").pop());
                    if (v !== null && (best === null || v > best)) best = v;
                }
                if (best !== null && best >= n) return;
                for (const k of keys)await c.delete(k);
                await c.put(new root.Request(urlOf(n)), new root.Response("", {
                    status: 200
                }));
            })
    };
}
