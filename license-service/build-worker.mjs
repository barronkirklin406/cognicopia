#!/usr/bin/env node
/* =====================================================================
   One file for Cloudflare.

   Cloudflare's web editor takes a single file, so this joins the five
   modules in license-service/src/ and the Worker entry (worker.mjs) into
   license-service/dist/worker.js. Nothing is rewritten except the
   import and export keywords; the code is the code the tests run.

     node license-service/build-worker.mjs           write the file
     node license-service/build-worker.mjs --check   fail if the file is out of date (part of npm test)
   ===================================================================== */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ORDER = ["token", "stripe", "redeem", "email", "handlers"];   // each module after the ones it imports
const OUT = path.join(HERE, "dist", "worker.js");

export function bundle() {
  const parts = ["/* Cognicopia license service, one file for Cloudflare Workers. Generated by license-service/build-worker.mjs from license-service/src/*.mjs: change those, not this. */"];
  for (const name of ORDER) {
    const src = fs.readFileSync(path.join(HERE, "src", name + ".mjs"), "utf8");
    const body = src
      .replace(/^import\s[^;]*;\s*$/gm, "")
      .replace(/^export\s+(?=(?:async\s+function|function|class|const|let)\b)/gm, "");
    if (/^\s*(?:import|export)\s/m.test(body)) throw new Error(`${name}.mjs has an import or export this bundler does not handle`);
    parts.push(`/* ---------- ${name}.mjs ---------- */`, body.trim());
  }
  parts.push("export default { fetch: (request, env) => route(request, env) };");
  return parts.join("\n\n") + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = bundle();
  if (process.argv.includes("--check")) {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : null;
    if (have !== text) { console.error("license-service/dist/worker.js is out of date. Run: node license-service/build-worker.mjs"); process.exit(1); }
    console.log("worker bundle is current (" + text.length + " bytes)");
  } else {
    fs.mkdirSync(path.dirname(OUT), { recursive: true });
    fs.writeFileSync(OUT, text);
    console.log("wrote license-service/dist/worker.js (" + text.length + " bytes)");
  }
}
