#!/usr/bin/env node
/* =====================================================================
   Builds the TypeScript services (src/services/*.ts) into plain browser
   scripts (assets/services/*.js) that the Packet Builder and the packet
   tool load with an ordinary <script> tag and use offline.

   Node's own type stripper does the work (node:module, no packages): the
   types come off, and the module's exports become one frozen global,
   named by the "@global Name" line in the source's header comment:
       src/services/vectorEngine.ts  ->  globalThis.CogniVectorEngine
   The services use only erasable TypeScript (no enums or namespaces) and
   no runtime imports, so the browser file is exactly the checked source.

   Run:  node scripts/build-services.mjs           write the scripts
         node scripts/build-services.mjs --check   verify they are current
   Type checking: tsc -p tsconfig.json (npm test runs it when tsc is installed).
   ===================================================================== */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import { stripTypeScriptTypes } from "node:module";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "src", "services"), OUT = path.join(ROOT, "assets", "services");
const CHECK = process.argv.includes("--check");
process.removeAllListeners("warning");                      // the stripper announces itself as experimental

export function buildService(file){
  const ts = fs.readFileSync(path.join(SRC, file), "utf8");
  const global = (/@global\s+([A-Za-z_$][\w$]*)/.exec(ts) || [])[1];
  if (!global) throw new Error(`${file}: add "@global Name" to its header comment`);
  let js = stripTypeScriptTypes(ts, { mode:"transform", sourceMap:false });
  const names = [];
  js = js.replace(/^export (async function\*?|function\*?|const|let|var|class) ([A-Za-z_$][\w$]*)/gm, (m, kw, n) => { names.push(n); return kw + " " + n; });
  js = js.replace(/^export \{([^}]*)\};?[ \t]*$/gm, (m, list) => { list.split(",").map(x => x.trim()).filter(Boolean).forEach(x => { const [a, b] = x.split(/\s+as\s+/); names.push(b ? `${b}: ${a}` : a); }); return ""; });
  if (/^\s*(import|export)\b/m.test(js)) throw new Error(`${file}: runtime imports or exports the build cannot turn into a global`);
  const header = `/* ${global}: built from src/services/${file} by scripts/build-services.mjs.\n   Do not edit this file: edit the TypeScript source and run npm run services. */\n`;
  return header + `(function(root){\n"use strict";\n${js.trim()}\nroot.${global} = Object.freeze({ ${names.join(", ")} });\n})(typeof globalThis !== "undefined" ? globalThis : this);\n`;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain){
  const files = fs.readdirSync(SRC).filter(f => f.endsWith(".ts") && !f.endsWith(".d.ts")).sort();
  const stale = [];
  for (const f of files){
    const out = path.join(OUT, f.replace(/\.ts$/, ".js")), js = buildService(f);
    const cur = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : null;
    if (cur === js) continue;
    if (CHECK){ stale.push(path.relative(ROOT, out)); continue; }
    fs.mkdirSync(OUT, { recursive:true }); fs.writeFileSync(out, js);
    console.log("wrote " + path.relative(ROOT, out));
  }
  if (CHECK && stale.length){ console.error("Out of date (run npm run services): " + stale.join(", ")); process.exit(1); }
  console.log(`${files.length} service(s) ${CHECK ? "current" : "built"}: ${files.join(", ")}`);
}
