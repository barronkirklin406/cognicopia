#!/usr/bin/env node
/* =====================================================================
   Makes css/pages-utilities.css: the utility classes (Tailwind names) that
   batch-scheduler.html and family-bridge.html use, as one plain stylesheet
   that ships with the site.

   Those two pages used to load cdn.tailwindcss.com, a script from outside,
   which no page of this site may do. This replaces it: the CSS is made here,
   once, from the pages' own text, and committed. The pages link the file;
   nothing is fetched when they open.

   Run:  node scripts/make-pages-css.mjs            (rewrite the file)
         node scripts/make-pages-css.mjs --check    (fail if it is out of date)

   It is an owner/developer tool, not part of the site: it needs Tailwind,
   which `npm install` in platform/ provides (nothing is added to the site).
   Re-run it after changing the classes in either page or in the scripts
   those pages load, then commit the result. Never edit the output by hand.
   ===================================================================== */
import fs from "fs";
import path from "path";
import { createRequire } from "module";
import { fileURLToPath } from "url";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "css/pages-utilities.css");
const SOURCES = ["batch-scheduler.html", "family-bridge.html", "assets/services/batchSchedulerEngine.js", "assets/services/familyBridgeStore.js"];

const platform = createRequire(path.join(ROOT, "platform/package.json"));
let postcss, tailwind;
try {
  postcss = platform("postcss");
  tailwind = platform("@tailwindcss/postcss");
} catch {
  console.error("Tailwind is not installed. Run `npm install` in platform/ first.");
  process.exit(2);
}

const tailwindDir = path.dirname(platform.resolve("tailwindcss/package.json"));
const input = [
  `@import "${path.join(tailwindDir, "theme.css")}" layer(theme);`,
  `@import "${path.join(tailwindDir, "preflight.css")}" layer(base);`,
  `@import "${path.join(tailwindDir, "utilities.css")}" layer(utilities);`,
  ...SOURCES.map((s) => `@source "${path.join(ROOT, s)}";`),
].join("\n");

const result = await postcss([tailwind({ optimize: { minify: false } })]).process(input, { from: path.join(ROOT, "css/pages-utilities.src.css") });
const banner = "/* Generated by scripts/make-pages-css.mjs from the classes in batch-scheduler.html, family-bridge.html and the scripts they load. Do not edit by hand. */\n";
const css = banner + result.css.replace(/\/\*! tailwindcss[^*]*\*\/\n?/g, "").trim() + "\n";

if (process.argv.includes("--check")) {
  const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
  if (current !== css) {
    console.error("css/pages-utilities.css is out of date. Run: node scripts/make-pages-css.mjs");
    process.exit(1);
  }
  console.log("css/pages-utilities.css is current.");
} else {
  fs.writeFileSync(OUT, css);
  console.log(`Wrote css/pages-utilities.css (${css.length} bytes).`);
}
