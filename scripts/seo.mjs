#!/usr/bin/env node
/* =====================================================================
   Findability: sitemap.xml, robots.txt, and what every public page says
   about itself to a search engine or a shared link.

     node scripts/seo.mjs           write sitemap.xml, robots.txt, and the head block of each page
     node scripts/seo.mjs --check   fail if any of it is out of date or wrong
                                    (part of npm test and npm run build)

   What is written
     sitemap.xml   every public page (no tool screens, no purchase page, no
                   redirect stub), with no "last modified" date it cannot back
     robots.txt    everything may be read except the purchase-activation page
                   and the Packet Builder's own screens; it names the sitemap
     head block    between <!-- seo:start --> and <!-- seo:end --> in each
                   handwritten page: the canonical address, the Open Graph
                   and Twitter card tags that a shared link shows. (The
                   Research Center's pages are made by scripts/research-pages.mjs,
                   which writes their canonical address itself.)
     JSON-LD       a SoftwareApplication block on the front page whose prices
                   are read from src/config/license.js, the one place prices live

   What is checked
     every public page has a title, one meta description of 70 to 320
     characters that no other page shares, and exactly one canonical address
     that is its own; the sitemap lists exactly the public pages; the JSON-LD
     parses and its prices are the ones in src/config/license.js; nothing in
     the sitemap points at a redirect stub or a page that does not exist.

   Node built-ins only.
   ===================================================================== */
import fs from "fs";
import path from "path";
import vm from "vm";
import { fileURLToPath } from "url";
import { MODULES, researchDocs } from "./site-nav.mjs";

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://cognicopia.org";
const check = process.argv.includes("--check");
const read = f => fs.readFileSync(path.join(ROOT, f), "utf8");
const esc = s => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");
const START = "<!-- seo:start: generated by scripts/seo.mjs. Edit that file and run node scripts/seo.mjs; changes made here are overwritten. -->", END = "<!-- seo:end -->";
const JSONLD_START = '<script type="application/ld+json" id="ld-software">', JSONLD_END = "</script>";

/* ---------- the public pages ---------- */
const HAND = ["index.html", "pricing.html", "pilot.html", "referral.html", "contact.html", "life-planners.html", "cognitive-journals.html", "zentangle-art.html", "resources/index.html"]
  .concat(MODULES.filter(m => m.slug !== "research").map(m => "resources/" + m.slug + "/index.html"));
const GENERATED = ["resources/research/index.html"].concat(researchDocs().map(d => "resources/research/" + d.slug + "/index.html"));   // written by scripts/research-pages.mjs
const PUBLIC = HAND.concat(GENERATED);
const urlOf = file => SITE + "/" + file.replace(/index\.html$/, "");

/* every page that is not public, and why: nothing else may sit in the repository's root unexplained */
const NOT_PUBLIC = {
  "builder.html": "the Packet Builder app", "profile.html": "the resident profile form (a tool screen)", "activate.html": "turns a purchase into a key",
  "about.html": "redirect stub", "faq.html": "redirect stub", "features.html": "redirect stub", "resources.html": "redirect stub", "high-volume-facilities.html": "redirect stub",
  "clinical-alignment.html": "redirect stub", "publishing-excellence.html": "redirect stub", "institutional-standards.html": "redirect stub", "therapy.html": "redirect stub"
};

const tagOf = (html, re) => { const m = re.exec(html); return m ? m[1] : null; };
const titleOf = html => tagOf(html, /<title>([^<]*)<\/title>/);
const descOf = html => tagOf(html, /<meta name="description" content="([^"]*)"/);
const unesc = s => s.replace(/&quot;/g, '"').replace(/&lt;/g, "<").replace(/&gt;/g, ">").replace(/&amp;/g, "&");

function headBlock(file, html){
  const title = titleOf(html), desc = descOf(html);
  if (!title || !desc) throw new Error(file + ": needs a <title> and a meta description before its head block can be made");
  return [START,
    `<link rel="canonical" href="${urlOf(file)}">`,
    `<meta property="og:site_name" content="Cognicopia">`,
    `<meta property="og:type" content="website">`,
    `<meta property="og:title" content="${title}">`,
    `<meta property="og:description" content="${desc}">`,
    `<meta property="og:url" content="${urlOf(file)}">`,
    `<meta property="og:image" content="${SITE}/cognicopia-logo.jpg">`,
    `<meta name="twitter:card" content="summary">`,
    END].join("\n");
}
function withHead(file, html){
  const block = headBlock(file, html), a = html.indexOf(START.slice(0, 18)), b = a < 0 ? -1 : html.indexOf(END, a);
  if (a >= 0 && b >= 0) return html.slice(0, a) + block + html.slice(b + END.length);
  const i = html.indexOf("</head>"); if (i < 0) throw new Error(file + ": no </head>");
  return html.slice(0, i) + block + "\n" + html.slice(i);
}

/* ---------- the prices, from the one place they live ---------- */
function config(){
  const ctx = vm.createContext({}); vm.runInContext(read("src/config/license.js"), ctx);
  return ctx.CognicopiaLicenseConfig;
}
function softwareLd(){
  const C = config(), P = C.PRICES;
  const offer = (name, amount, per, extra) => Object.assign({ "@type": "Offer", name, priceCurrency: "USD", price: String(amount), url: SITE + "/pricing.html",
    priceSpecification: { "@type": "UnitPriceSpecification", price: String(amount), priceCurrency: "USD", billingDuration: per === "month" ? "P1M" : per === "year" ? "P1Y" : undefined, unitText: per ? per : undefined } }, extra || {});
  const ld = {
    "@context": "https://schema.org",
    "@type": "SoftwareApplication",
    name: "Cognicopia",
    url: SITE + "/",
    description: "Personalized activity packets, coloring pages, life planners and journals for memory care, made in the browser. No resident data leaves the device.",
    applicationCategory: "HealthApplication",
    operatingSystem: "Any computer with a web browser",
    publisher: { "@type": "Organization", name: "Cognicopia", url: SITE + "/" },
    offers: [
      { "@type": "Offer", name: "Free start: " + C.FREE_RUNS + " packets", price: "0", priceCurrency: "USD", url: SITE + "/pilot.html" },
      offer("Monthly facility license", P.monthly.amount, P.monthly.per),
      offer("Annual facility license", P.annual.amount, P.annual.per)
    ]
  };
  return JSON.stringify(ld, null, 2);
}
function withLd(html){
  const block = JSONLD_START + "\n" + softwareLd() + "\n" + JSONLD_END, a = html.indexOf(JSONLD_START);
  if (a >= 0){ const b = html.indexOf(JSONLD_END, a); return html.slice(0, a) + block + html.slice(b + JSONLD_END.length); }
  const i = html.indexOf(END); return html.slice(0, i + END.length) + "\n" + block + html.slice(i + END.length);
}

/* ---------- sitemap and robots ---------- */
const sitemap = () => `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  PUBLIC.map(f => `  <url><loc>${urlOf(f)}</loc></url>`).join("\n") + `\n</urlset>\n`;
const robots = () => `# Cognicopia: everything may be read except the purchase-activation page and the Packet Builder's own screens.\nUser-agent: *\nAllow: /\nDisallow: /activate.html\nDisallow: /builder.html\n\nSitemap: ${SITE}/sitemap.xml\n`;

/* ---------- write, or check ---------- */
const problems = []; let passed = 0;
const ok = (cond, msg) => { if (cond) passed++; else problems.push(msg); };
const stale = [];
function put(file, text){
  const f = path.join(ROOT, file), have = fs.existsSync(f) ? fs.readFileSync(f, "utf8") : null;
  if (have === text) return;
  if (check) { stale.push(file); return; }
  fs.writeFileSync(f, text); console.log("wrote " + file);
}

for (const file of HAND){
  if (!fs.existsSync(path.join(ROOT, file))) { problems.push(file + " is listed as public and does not exist"); continue; }
  let html = read(file);
  try { html = withHead(file, html); if (file === "index.html") html = withLd(html); } catch (e) { problems.push(e.message); continue; }
  put(file, html);
}
put("sitemap.xml", sitemap());
put("robots.txt", robots());
if (stale.length) problems.push("out of date: " + stale.join(", ") + ". Run: node scripts/seo.mjs");

/* ---------- the proof ---------- */
const seenDesc = new Map(), seenTitle = new Map();
for (const file of PUBLIC){
  if (!fs.existsSync(path.join(ROOT, file))) continue;
  const html = read(file), title = titleOf(html), desc = descOf(html) && unesc(descOf(html));
  ok(!!title && title.trim().length >= 10, file + ": has a title of its own");
  ok(!!desc && desc.length >= 70 && desc.length <= 320, file + ": a meta description of 70 to 320 characters (" + (desc ? desc.length : "none") + ")");
  if (desc){ if (seenDesc.has(desc)) problems.push(file + ": shares its meta description with " + seenDesc.get(desc)); else seenDesc.set(desc, file); }
  if (title){ const t = unesc(title); if (seenTitle.has(t)) problems.push(file + ": shares its title with " + seenTitle.get(t)); else seenTitle.set(t, file); }
  const canon = [...html.matchAll(/<link rel="canonical" href="([^"]*)"/g)].map(m => m[1]);
  ok(canon.length === 1 && canon[0] === urlOf(file), file + ": exactly one canonical address, and it is its own (" + canon.join(", ") + ")");
  ok((html.match(/<meta name="robots" content="[^"]*noindex/g) || []).length === 0, file + ": is public and must not say noindex");
}
for (const [file, why] of Object.entries(NOT_PUBLIC)){
  ok(!PUBLIC.includes(file), file + " (" + why + ") must not be in the sitemap");
  if (why === "redirect stub" && fs.existsSync(path.join(ROOT, file))) ok(/noindex/.test(read(file)), file + ": a redirect stub says noindex");
}
const rootPages = fs.readdirSync(ROOT).filter(f => f.endsWith(".html"));
for (const f of rootPages) ok(PUBLIC.includes(f) || f in NOT_PUBLIC, f + ": is neither in the sitemap nor explained in scripts/seo.mjs (NOT_PUBLIC)");

if (fs.existsSync(path.join(ROOT, "sitemap.xml"))){
  const locs = [...read("sitemap.xml").matchAll(/<loc>([^<]*)<\/loc>/g)].map(m => m[1]);
  ok(locs.length === PUBLIC.length && new Set(locs).size === locs.length, "the sitemap lists each public page once (" + locs.length + ")");
  for (const l of locs) ok(l.startsWith(SITE + "/") && fs.existsSync(path.join(ROOT, l.slice(SITE.length + 1) + (l.endsWith("/") || l === SITE + "/" ? "index.html" : ""))), "sitemap: " + l + " is a page on this site");
}
ok(/Sitemap: https:\/\/cognicopia\.org\/sitemap\.xml/.test(fs.existsSync(path.join(ROOT, "robots.txt")) ? read("robots.txt") : ""), "robots.txt names the sitemap");

/* the front page's JSON-LD: parses, and says the prices license.js says */
{
  const html = read("index.html"), a = html.indexOf(JSONLD_START), b = a < 0 ? -1 : html.indexOf(JSONLD_END, a);
  ok(a >= 0 && b > a, "index.html carries the SoftwareApplication JSON-LD");
  if (a >= 0 && b > a){
    let ld = null; try { ld = JSON.parse(html.slice(a + JSONLD_START.length, b)); } catch (e) { problems.push("index.html: the JSON-LD does not parse: " + e.message); }
    if (ld){
      const P = config().PRICES, prices = ld.offers.map(o => o.price).join(",");
      ok(ld["@type"] === "SoftwareApplication" && ld.offers.length === 3, "the JSON-LD is a SoftwareApplication with three offers");
      ok(prices === ["0", P.monthly.amount, P.annual.amount].join(","), "the JSON-LD prices (" + prices + ") are the ones in src/config/license.js (0, " + P.monthly.amount + ", " + P.annual.amount + ")");
      ok(!/aggregateRating|review/i.test(JSON.stringify(ld)), "the JSON-LD makes no rating or review claim");
    }
  }
}

if (problems.length){ console.error(`seo check FAILED: ${problems.length} problem(s), ${passed} passed\n  - ` + problems.join("\n  - ")); process.exit(1); }
console.log(check ? `seo check passed: ${passed} checks (${PUBLIC.length} public pages: one canonical, a unique title and description each; sitemap.xml, robots.txt; the front page's JSON-LD prices match src/config/license.js)` : "seo files are written (" + PUBLIC.length + " public pages)");
